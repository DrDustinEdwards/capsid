import assert from "node:assert/strict";
import { test } from "node:test";
import { stripFooter } from "../scripts/strip-pr-footer.mjs";

// The footer a cloud session's GitHub connection appends to pull request descriptions
// (scripts/strip-pr-footer.mjs; .github/workflows/ai-author.yml).

test("PLANT: the connection's footer is removed, whichever link it carries", () => {
  const body = "Before: x.\n\nCloses job_0368576da167.\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01Abc)_";
  assert.equal(stripFooter(body), "Before: x.\n\nCloses job_0368576da167.\n");
  assert.equal(stripFooter("Text.\n\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"), "Text.\n");
});

test("the older wording, a bare line and a session link are removed too", () => {
  assert.equal(stripFooter("Text.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_01CvxjrzauAEyAG5rwYUfs7C"), "Text.\n");
  assert.equal(stripFooter("Text.\n_Generated by [Claude Code](https://claude.ai/code)_"), "Text.\n");
});

test("a description with no footer, a rule in the middle, or a mention in prose is left alone", () => {
  assert.equal(stripFooter("Before.\n\n---\n\nAfter."), null);
  assert.equal(stripFooter("We tried Generated by [Claude Code](https://claude.ai/code)_ in the middle.\n\nMore text."), null);
  assert.equal(stripFooter(null), null);
  assert.equal(stripFooter(""), null);
});

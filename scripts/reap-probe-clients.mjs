#!/usr/bin/env node
// Deletes the ONE OAuth client registration that this run's scripts/verify-live.mjs
// created. Nothing else. It does not list the namespace, it does not match on a client
// name, and it cannot discover a key it was not told about.
//
// Gate 2 must register a FRESH client every run (see verify-live.mjs), so the probe
// clients are cleaned up afterwards rather than reused.
//
// ONE ID, never a match on client name: /register is unauthenticated, so any caller
// chooses its own client_name, and a delete rule keyed on that string is one anyone can
// aim. It also never reads the rest of the keyspace.
//
// No wrangler and no node_modules. This runs in the live job, which skips npm ci so the
// gate still works when install is broken, so it talks to the KV REST API with global
// fetch and nothing else.

import { readFileSync } from "node:fs";
import { OAUTH_KV } from "./bindings.mjs";
import { reapProbeClient, reportFor } from "./reap-lib.mjs";

const ACCOUNT = process.env.CLOUDFLARE_ACCOUNT_ID;
const TOKEN = process.env.CLOUDFLARE_API_TOKEN;
// The probe client lives in the OAuth provider's keyspace, so this deletes from OAUTH_KV
// and nothing else. The id comes from scripts/bindings.mjs, the single place any binding
// id is written.
const NAMESPACE_ID = OAUTH_KV.id;

// The id comes from the run that created it: --client <id>, or the file
// verify-live.mjs writes when PROBE_CLIENT_FILE is set. No discovery.
function resolveClientId() {
  const flag = process.argv.indexOf("--client");
  if (flag !== -1 && process.argv[flag + 1]) return process.argv[flag + 1].trim();
  const file = process.env.PROBE_CLIENT_FILE;
  if (!file) return null;
  try {
    return readFileSync(file, "utf8").trim() || null;
  } catch (err) {
    // Only a file that is NOT THERE means gate 2 registered nothing. A file that is
    // there and cannot be read may name a client that is now left behind, so it fails.
    if (/** @type {NodeJS.ErrnoException} */ (err).code === "ENOENT") return null;
    console.error(`reap: could not read ${file}: ${/** @type {Error} */ (err).message}`);
    process.exit(1);
  }
}

const clientId = resolveClientId();

// Nothing registered means nothing to delete: verify-live.mjs writes the file the moment
// gate 2 succeeds. Printed, so the step is visibly not a no-op.
if (!clientId) {
  console.log("reap: no probe client id recorded (gate 2 did not register one). Nothing to delete.");
  process.exit(0);
}

if (!ACCOUNT || !TOKEN) {
  console.error("reap: CLOUDFLARE_ACCOUNT_ID and CLOUDFLARE_API_TOKEN are required. Refusing to run blind.");
  process.exit(1);
}

// A client id is generated by the provider and appears in a URL path here, so it is
// checked rather than trusted. Anything outside this shape is a bug in the caller.
if (!/^[A-Za-z0-9_-]{8,64}$/.test(clientId)) {
  console.error(`reap: refusing to delete an implausible client id: ${JSON.stringify(clientId.slice(0, 80))}`);
  process.exit(1);
}

const key = `client:${clientId}`;
const BASE = `https://api.cloudflare.com/client/v4/accounts/${ACCOUNT}/storage/kv/namespaces/${NAMESPACE_ID}`;
const auth = { Authorization: `Bearer ${TOKEN}` };

// READ, then delete, then read back. The decision lives in ./reap-lib.mjs so it can
// be tested; see that file for why the pre-read is the part that matters.
const { outcome, status, detail } = await reapProbeClient({ fetchImpl: fetch, base: BASE, key, auth });
const { ok, message } = reportFor(outcome, key);
const suffix = [status ? `status ${status}` : "", detail ? detail : ""].filter(Boolean).join(" ");
if (ok) {
  console.log(message);
  process.exit(0);
}
console.error(suffix ? `${message} (${suffix})` : message);
process.exit(1);
